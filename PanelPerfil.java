    public PanelPerfil(MenuPrincipal menu) {
        this.menu = menu;
        initComponents();
        construirInterfaz();
    }

    private void construirInterfaz() {
        setLayout(new BorderLayout(0, 20));
        setBackground(Estilo.FONDO);

        JPanel norte = new JPanel(new BorderLayout(0, 4));
        norte.setOpaque(false);
        norte.add(Estilo.encabezado("Mi perfil"), BorderLayout.NORTH);
        norte.add(Estilo.subtitulo("Actualiza tus datos personales"), BorderLayout.CENTER);

        txtNombre = new JTextField(25);
        txtCarrera = new JTextField(25);
        txtCorreo = new JTextField(25);

        JPanel tarjeta = Estilo.tarjeta();
        tarjeta.setLayout(new GridBagLayout());
        GridBagConstraints c = new GridBagConstraints();
        c.insets = new Insets(8, 5, 8, 5);
        c.anchor = GridBagConstraints.WEST;

        agregarFila(tarjeta, c, 0, "Nombre", txtNombre);
        agregarFila(tarjeta, c, 1, "Carrera", txtCarrera);
        agregarFila(tarjeta, c, 2, "Correo institucional", txtCorreo);

        JButton guardar = Estilo.boton("Guardar cambios", true);
        guardar.addActionListener(e -> guardar());
        c.gridx = 1;
        c.gridy = 3;
        c.fill = GridBagConstraints.NONE;
        tarjeta.add(guardar, c);

        JPanel contenedor = new JPanel(new BorderLayout());
        contenedor.setOpaque(false);
        contenedor.add(tarjeta, BorderLayout.NORTH);

        add(norte, BorderLayout.NORTH);
        add(contenedor, BorderLayout.CENTER);

        cargar();
        addComponentListener(new ComponentAdapter() {
            @Override
            public void componentShown(ComponentEvent e) {
                cargar();
            }
        });
    }

    private void agregarFila(JPanel p, GridBagConstraints c, int fila, String texto, JTextField campo) {
        c.gridx = 0;
        c.gridy = fila;
        c.fill = GridBagConstraints.NONE;
        c.weightx = 0;
        JLabel l = new JLabel(texto);
        l.setForeground(Estilo.MORADO_OSCURO);
        p.add(l, c);
        c.gridx = 1;
        c.fill = GridBagConstraints.HORIZONTAL;
        c.weightx = 1;
        p.add(campo, c);
    }

    private void cargar() {
        Estudiante est = menu.getSistema().getEstudiante();
        txtNombre.setText(est.getNombre());
        txtCarrera.setText(est.getCarrera());
        txtCorreo.setText(est.getCorreo());
    }

    private void guardar() {
        Estudiante est = menu.getSistema().getEstudiante();
        try {
            new Estudiante(txtNombre.getText(), txtCorreo.getText(), txtCarrera.getText());
            est.setNombre(txtNombre.getText());
            est.setCorreo(txtCorreo.getText());
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Perfil", JOptionPane.WARNING_MESSAGE);
            return;
        }
        est.setCarrera(txtCarrera.getText());
        menu.guardarYRefrescar();
        JOptionPane.showMessageDialog(this, "Perfil actualizado.", "Perfil", JOptionPane.INFORMATION_MESSAGE);
    }

