    private void estilizarBoton(javax.swing.JButton b) {
    b.setBackground(MORADO_OSCURO);
    b.setForeground(BLANCO);
    b.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 14));
    b.setFocusPainted(false);
    b.setBorderPainted(false);
    b.setHorizontalAlignment(javax.swing.SwingConstants.LEFT);
    b.setBorder(javax.swing.BorderFactory.createEmptyBorder(10, 20, 10, 10));
    b.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));

    b.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseEntered(java.awt.event.MouseEvent e) {
            b.setBackground(NARANJA);
            b.setForeground(MORADO_OSCURO);
        }
        @Override
        public void mouseExited(java.awt.event.MouseEvent e) {
            b.setBackground(MORADO_OSCURO);
            b.setForeground(BLANCO);
        }
    });
}

public void mostrarPanel(String nombre) {
    java.awt.CardLayout cl = (java.awt.CardLayout) pnlContenido.getLayout();
    cl.show(pnlContenido, nombre);
}

public void actualizarDatos(String nombre, int dunab, int inscritos) {
    lblUsuario.setText("Bienvenido, " + nombre);
    prgDunab.setValue(dunab);
    lblDunab.setText(dunab + " / 10.000 DUNAB");
    panelinicio.actualizarDatos(nombre, dunab, inscritos);
}
