    private JPanel crearTarjeta() {
        JPanel p = new JPanel();
        p.setBackground(Color.WHITE);
        p.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(new Color(0xE4D9F0)),
                BorderFactory.createEmptyBorder(15, 20, 15, 20)));
        return p;
    }

    private JPanel crearTarjetaDato(String titulo, JLabel valor, Color colorValor) {
        JPanel p = crearTarjeta();
        p.setLayout(new BorderLayout(0, 6));
        JLabel t = new JLabel(titulo);
        t.setForeground(new Color(0x777777));
        valor.setFont(new Font("Segoe UI", Font.BOLD, 32));
        valor.setForeground(colorValor);
        p.add(t, BorderLayout.NORTH);
        p.add(valor, BorderLayout.CENTER);
        return p;
    }

    private JButton crearBotonAccion(String texto, String panel, boolean principal) {
        JButton b = new JButton(texto);
        b.setFont(new Font("Segoe UI", Font.BOLD, 14));
        b.setFocusPainted(false);
        b.setCursor(new Cursor(Cursor.HAND_CURSOR));
        if (principal) {
            b.setBackground(MORADO);
            b.setForeground(Color.WHITE);
        } else {
            b.setBackground(NARANJA);
            b.setForeground(MORADO_OSCURO);
        }
        b.addActionListener(e -> menu.mostrarPanel(panel));
        return b;
    }

    public void actualizarDatos(String nombre, int dunab, int inscritos) {
        int meta = 10000;
        int faltan = Math.max(0, meta - dunab);
        lblBienvenida.setText("¡Hola, " + nombre + "!");
        lblAcumulados.setText(String.valueOf(dunab));
        lblFaltan.setText(String.valueOf(faltan));
        lblInscritos.setText(String.valueOf(inscritos));
        barra.setValue(Math.min(dunab, meta));
        lblPorcentaje.setText((dunab * 100 / meta) + "% completado");
    }
